			"Nano" => Nano(),
			"Plant" => Plant(),
			"Cave" => Cave(),
			"Wanderer" => Wanderer(),
			_ => new List<TutorialPage>(),
		};

		private static TutorialPage Page(string title, params string[] lines)
		{
			var p = new TutorialPage { Section = "核心机制", Title = title };
			p.Lines.AddRange(lines);
			return p;
		}

