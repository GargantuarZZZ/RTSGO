	//   这类**设计意图与打法结论**在配置里根本没有，必须人来写。
	//
	// 写作纪律：
	//   1. 只写**代码里确实实现**的机制；凡有数值，都在 TutorialCodex
	//      生成的档案页里，这里只给结论与打法，不重复抄数字。
	//   2. 每条机制都要能落到"所以你该怎么打"，而不是百科式的功能罗列。
	//   3. 依据来源：各 *.tres 的字段注释 + 设计/设计数据表。
	// =========================================================

